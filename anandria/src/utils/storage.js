import { STORAGE_KEYS } from './constants.js';

/**
 * Save data to localStorage with error handling.
 */
export function saveToStorage(key, data) {
  try {
    localStorage.setItem(key, JSON.stringify(data));
    return true;
  } catch (err) {
    console.warn('[ANANDRIA] Failed to save to localStorage:', err);
    return false;
  }
}

/**
 * Load data from localStorage with error handling.
 */
export function loadFromStorage(key, defaultValue = null) {
  try {
    const item = localStorage.getItem(key);
    if (item === null) return defaultValue;
    return JSON.parse(item);
  } catch (err) {
    console.warn('[ANANDRIA] Failed to load from localStorage:', err);
    return defaultValue;
  }
}

/**
 * Remove a key from localStorage.
 */
export function removeFromStorage(key) {
  try {
    localStorage.removeItem(key);
  } catch (err) {
    console.warn('[ANANDRIA] Failed to remove from localStorage:', err);
  }
}

/**
 * Clear all ANANDRIA data from localStorage.
 */
export function clearAllStorage() {
  Object.values(STORAGE_KEYS).forEach((key) => removeFromStorage(key));
}

/**
 * Generate a unique cache key based on event form data.
 * Used to avoid redundant API calls for the same input.
 */
export function generateCacheKey(formData) {
  const { eventType, eventName, targetDate, guestCount, totalBudget, currency, themeKeywords } = formData;
  return btoa(
    `${eventType}|${eventName}|${targetDate}|${guestCount}|${totalBudget}|${currency}|${themeKeywords}`
  ).slice(0, 32);
}

/**
 * Export event plan as a formatted JSON string.
 */
export function exportToJSON(plan, formData) {
  const exportData = {
    exportedAt: new Date().toISOString(),
    eventDetails: formData,
    plan,
  };
  const blob = new Blob([JSON.stringify(exportData, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `anandria-plan-${formData.eventName?.replace(/\s+/g, '-') || 'event'}.json`;
  link.click();
  URL.revokeObjectURL(url);
}

/**
 * Export event plan as a Markdown summary.
 */
export function exportToMarkdown(plan, formData) {
  const { eventName, eventType, targetDate, guestCount, totalBudget, currency } = formData;
  const currencySymbol = { INR: '₹', USD: '$', EUR: '€', GBP: '£' }[currency] || '₹';

  let md = `# ${eventName} – Event Plan\n`;
  md += `**Type**: ${eventType} | **Date**: ${targetDate} | **Guests**: ${guestCount} | **Budget**: ${currencySymbol}${Number(totalBudget).toLocaleString()}\n\n`;
  md += `> Generated by ANANDRIA – GenAI Event Planning Co-Pilot\n\n`;

  md += `## 💰 Budget Breakdown\n`;
  (plan.budgetBreakdown || []).forEach((item) => {
    md += `- **${item.category}**: ${currencySymbol}${Number(item.amount).toLocaleString()} (${item.percentage?.toFixed(1)}%)\n`;
    if (item.notes) md += `  _${item.notes}_\n`;
  });

  md += `\n## 📅 Timeline & Milestones\n`;
  (plan.timeline || []).forEach((m) => {
    md += `- [${m.completed ? 'x' : ' '}] **${m.phase}**: ${m.task} _(${m.dueDate})_\n`;
  });

  md += `\n## 🏢 Vendor Checklist\n`;
  (plan.vendorChecklist || []).forEach((v) => {
    md += `- [${v.status === 'Booked' ? 'x' : ' '}] **${v.vendor}** – ${v.task} | Status: ${v.status} | Priority: ${v.priority}\n`;
    if (v.estimatedCost) md += `  _Est. Cost: ${currencySymbol}${v.estimatedCost}_\n`;
  });

  md += `\n## 💡 Ideas & Inspiration\n`;
  const ideas = plan.personalizedIdeas;
  if (ideas) {
    if (ideas.themes) {
      md += `### Themes\n`;
      ideas.themes.forEach((t) => md += `- **${t.name}**: ${t.description}\n`);
    }
    if (ideas.colorPalettes) {
      md += `### Color Palettes\n`;
      ideas.colorPalettes.forEach((p) => md += `- **${p.name}**: ${p.colors?.join(', ')}\n`);
    }
    if (ideas.menuIdeas) {
      md += `### Menu Ideas\n`;
      ideas.menuIdeas.forEach((m) => md += `- ${m}\n`);
    }
    if (ideas.activities) {
      md += `### Activities\n`;
      ideas.activities.forEach((a) => md += `- ${a}\n`);
    }
  }

  const blob = new Blob([md], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = `anandria-plan-${eventName?.replace(/\s+/g, '-') || 'event'}.md`;
  link.click();
  URL.revokeObjectURL(url);
}

/**
 * Debounce a function call.
 */
export function debounce(fn, delay) {
  let timer;
  return (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => fn(...args), delay);
  };
}
